// Helper to generate smooth realistic chart curves
function generateChartSeries(basePrice: number, volatility: number, trend: number, count: number): { time: string; price: number; volume?: number }[] {
  const points: { time: string; price: number; volume?: number }[] = [];
  let currentPrice = basePrice * (1 - (trend * 0.05));
  
  for (let i = 0; i < count; i++) {
    const randomStep = (Math.random() - 0.48) * volatility * basePrice * 0.01;
    const trendStep = (trend * basePrice * 0.001) / count;
    currentPrice = Math.max(currentPrice + randomStep + trendStep, basePrice * 0.5);
    
    let timeLabel = '';
    if (count <= 24) {
      timeLabel = `${String(9 + Math.floor(i * 0.35)).padStart(2, '0')}:${String((i * 15) % 60).padStart(2, '0')}`;
    } else if (count <= 30) {
      timeLabel = `Day ${i + 1}`;
    } else {
      timeLabel = `Wk ${i + 1}`;
    }

    points.push({
      time: timeLabel,
      price: Number(currentPrice.toFixed(2)),
      volume: Math.floor(Math.random() * 500000) + 100000
    });
  }
  return points;
}

function createAssetChart(basePrice: number, changePercent: number): Record<Timeframe, { time: string; price: number; volume?: number }[]> {
  const isUp = changePercent >= 0;
  const trend = isUp ? 1.2 : -1.2;
  return {
    '1D': generateChartSeries(basePrice, 0.4, trend, 24),
    '5D': generateChartSeries(basePrice * 0.98, 0.7, trend * 1.5, 30),
    '1M': generateChartSeries(basePrice * 0.95, 1.2, trend * 2, 30),
    '6M': generateChartSeries(basePrice * 0.9, 1.8, trend * 3, 35),
    '1Y': generateChartSeries(basePrice * 0.85, 2.5, trend * 4, 40),
    '5Y': generateChartSeries(basePrice * 0.6, 4.0, 3.5, 50),
    'ALL': generateChartSeries(basePrice * 0.35, 5.5, 4.2, 60),
  };
}

